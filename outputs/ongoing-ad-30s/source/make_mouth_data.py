#!/usr/bin/env python3
"""Mouth-open amount per video frame (30 fps) from the narration track: RMS loudness, normalised, lightly smoothed. Writes src/mouthData.ts.
usage: python make_mouth_data.py [narration_real.wav]"""
import subprocess, sys
from pathlib import Path
import numpy as np

HERE = Path(__file__).parent
wav = HERE / "public" / (sys.argv[1] if len(sys.argv) > 1 else "narration_real.wav")
sr = 16000
x = np.frombuffer(subprocess.run(["ffmpeg", "-v", "error", "-i", str(wav), "-f", "f32le", "-ac", "1", "-ar", str(sr), "-"], capture_output=True, check=True).stdout, dtype=np.float32)
n = int(len(x) / sr * 30)
rms = np.array([np.sqrt(np.mean(x[int(i / 30 * sr): int((i + 1) / 30 * sr)] ** 2) + 1e-12) for i in range(n)])
v = np.clip(rms / (np.percentile(rms, 95) + 1e-9), 0, 1)
v = np.convolve(v, [0.25, 0.5, 0.25], mode="same")
v = np.where(v < 0.08, 0, v)
(HERE / "src" / "mouthData.ts").write_text("// generated by make_mouth_data.py\nexport const MOUTH: number[] = " + str([round(float(a), 2) for a in v]) + ";\n")
print(n, "frames; speaking frames:", int((v > 0.1).sum()))
