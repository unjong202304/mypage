#!/usr/bin/env python3
"""Word timings for the karaoke captions, from the narration line files themselves (no speech recognition):
each line starts at its 'at' and lasts as long as its (trimmed) wav; real silences inside the wav (the pauses at commas) are detected
with ffmpeg and used as phrase boundaries; words are spread over each phrase by character count. Writes src/captionData.ts.
usage: python make_caption_timing.py [narration_real.json]   (run after make_narration.py with the same NARR_JSON)"""
import json, re, subprocess, sys
from pathlib import Path

HERE = Path(__file__).parent
lines = json.loads((HERE / (sys.argv[1] if len(sys.argv) > 1 else "narration_real.json")).read_text())
TMP = HERE / "public" / "_narration"


def probe(p):
    return float(subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(p)], capture_output=True, text=True).stdout)


def silences(p):
    r = subprocess.run(["ffmpeg", "-v", "info", "-i", str(p), "-af", "silencedetect=noise=-38dB:d=0.12", "-f", "null", "-"], capture_output=True, text=True).stderr
    st = [float(x) for x in re.findall(r"silence_start: ([\d.]+)", r)]
    en = [float(x) for x in re.findall(r"silence_end: ([\d.]+)", r)]
    return list(zip(st, en))


out = []
for i, ln in enumerate(lines):
    a, f = TMP / f"{i}.wav", TMP / f"{i}f.wav"
    wav = f if f.exists() and f.stat().st_mtime >= a.stat().st_mtime else a   # the sped-up copy only if it belongs to this run
    d = probe(wav)
    words = ln["text"].split()
    phrases, cur = [], []
    for w in words:
        cur.append(w)
        if w[-1] in ",.?!":
            phrases.append(cur); cur = []
    if cur: phrases.append(cur)
    inner = [(s, e) for s, e in silences(wav) if s > 0.15 and e < d - 0.05]          # pauses between phrases
    bounds = None
    if len(inner) >= len(phrases) - 1 and len(phrases) > 1:
        inner = sorted(sorted(inner, key=lambda x: x[0] - x[1])[: len(phrases) - 1])       # keep the longest pauses
        bounds = [(0.0, inner[0][0])] + [(inner[k][1], inner[k + 1][0]) for k in range(len(inner) - 1)] + [(inner[-1][1], d)]
    if bounds is None:
        bounds = [(0.0, d)]; phrases = [words]
    res = []
    for (s, e), ph in zip(bounds, phrases):
        tot = sum(len(w.replace(" ", "")) for w in ph); pos = 0
        for w in ph:
            n = len(w.replace(" ", ""))
            res.append({"w": w, "s": round(ln["at"] + s + (e - s) * pos / tot, 3), "e": round(ln["at"] + s + (e - s) * (pos + n) / tot, 3)}); pos += n
    out.append(res)
    print(f"line {i}: {res[0]['s']:.2f}-{res[-1]['e']:.2f}s ({len(bounds)} phrase(s), file {wav.name}) {ln['text'][:26]}")
(HERE / "src" / "captionData.ts").write_text("// generated by make_caption_timing.py\nexport const CAPTIONS: {w: string; s: number; e: number}[][] = " + json.dumps(out, ensure_ascii=False) + ";\n")
print("wrote src/captionData.ts")
